/*
 * Analog Accelerometer Logger for TM4C123G + BOOSTXL-EDUMKII (Educational
 * BoosterPack MK II)
 *
 * Reads X/Y/Z acceleration from the BoosterPack's accelerometer and streams it as
 * CSV text over UART0 (PA0/PA1). UART0 is bridged through the LaunchPad's
 * ICDI chip to a virtual COM port on the host over the same USB cable used
 * for flashing — no extra wiring required.
 *
 * IMPORTANT — the accelerometer on this BoosterPack is ANALOG, not I2C.
 * It is a 3-axis analog part whose X/Y/Z outputs are ratiometric voltages,
 * sampled here with ADC0. An earlier version of this firmware
 * tried to reach a BMI160 over I2C3; there is no BMI160 on the EDU MKII
 * (that part is on the BOOSTXL-SENSORS BoosterPack), and the only I2C
 * devices here are the TMP006 and OPT3001, which sit on BoosterPack pins
 * 9/10 -> PA6/PA7 -> I2C1 — not PD0/PD1.
 *
 * Wiring: the BoosterPack MK II stacks directly onto the LaunchPad headers.
 * The accelerometer axes are on BoosterPack header pins 23/24/25, which map to
 * this board as:
 *     pin 23 -> PD0 -> AIN7 -> accelerometer X
 *     pin 24 -> PD1 -> AIN6 -> accelerometer Y
 *     pin 25 -> PD2 -> AIN5 -> accelerometer Z
 * These pins must be configured as analog inputs: no digital enable, no
 * pull-ups, no open-drain, and definitely never driven as outputs — the
 * accelerometer is driving them.
 *
 * Each accelerometer sample is also run through a tiny 4-neuron spiking
 * liquid-time-constant (sLTC) network (see sltc_weights.h, generated by
 * training/train_sltc.py --export-cpp) to classify the current motion as
 * smooth vs turbulent in real time, driving the green/red status LED.
 *
 * Target: TM4C123GH6PM (Tiva C Series LaunchPad, EK-TM4C123GXL)
 * No TivaWare — direct register access only.
 */

#include <cstdint>
#include <cmath>

#include "sltcneuron.hpp"

/* ── Register access helper ─────────────────────────────────────────────── */
#define HWREG(addr) (*reinterpret_cast<volatile uint32_t *>(addr))

/* ── SYSCTL (clock gating) ──────────────────────────────────────────────── */
static constexpr uint32_t SYSCTL_RCGCGPIO = 0x400FE608;
static constexpr uint32_t SYSCTL_RCGCUART = 0x400FE618;
static constexpr uint32_t SYSCTL_RCGCADC  = 0x400FE638;
static constexpr uint32_t SYSCTL_PRGPIO   = 0x400FEA08;
static constexpr uint32_t SYSCTL_PRUART   = 0x400FEA18;
static constexpr uint32_t SYSCTL_PRADC    = 0x400FEA38;

/* ── GPIO Port A (UART0 on PA0/PA1) ─────────────────────────────────────── */
static constexpr uint32_t GPIOA_AFSEL = 0x40004420;
static constexpr uint32_t GPIOA_PCTL  = 0x4000452C;
static constexpr uint32_t GPIOA_DEN   = 0x4000451C;

/* ── GPIO Port D (accelerometer analog inputs on PD0/PD1/PD2) ─────────────────── */
static constexpr uint32_t GPIOD_DIR   = 0x40007400;
static constexpr uint32_t GPIOD_AFSEL = 0x40007420;
static constexpr uint32_t GPIOD_ODR   = 0x4000750C;
static constexpr uint32_t GPIOD_PUR   = 0x40007510;
static constexpr uint32_t GPIOD_DEN   = 0x4000751C;
static constexpr uint32_t GPIOD_AMSEL = 0x40007528;
static constexpr uint32_t ACCEL_PINS  = 0x07; /* PD0 = X, PD1 = Y, PD2 = Z */

/* ── GPIO Port F (status LED) ───────────────────────────────────────────── */
static constexpr uint32_t GPIOF_DIR       = 0x40025400;
static constexpr uint32_t GPIOF_DEN       = 0x4002551C;
static constexpr uint32_t GPIOF_DATA_ALL  = 0x400253FC;
static constexpr uint32_t LED_RED   = (1u << 1); /* PF1 */
static constexpr uint32_t LED_BLUE  = (1u << 2); /* PF2 */
static constexpr uint32_t LED_GREEN = (1u << 3); /* PF3 */

/* ── UART0 ───────────────────────────────────────────────────────────────── */
static constexpr uint32_t UART0_DR   = 0x4000C000;
static constexpr uint32_t UART0_FR   = 0x4000C018;
static constexpr uint32_t UART0_IBRD = 0x4000C024;
static constexpr uint32_t UART0_FBRD = 0x4000C028;
static constexpr uint32_t UART0_LCRH = 0x4000C02C;
static constexpr uint32_t UART0_CTL  = 0x4000C030;
static constexpr uint32_t UART_FR_TXFF = (1u << 5);

/* ── ADC0 (sample sequencer 0 — 8-deep FIFO, we use 3 slots) ────────────── */
static constexpr uint32_t ADC0_ACTSS   = 0x40038000;
static constexpr uint32_t ADC0_RIS     = 0x40038004;
static constexpr uint32_t ADC0_ISC     = 0x4003800C;
static constexpr uint32_t ADC0_EMUX    = 0x40038014;
static constexpr uint32_t ADC0_PSSI    = 0x40038028;
static constexpr uint32_t ADC0_SAC     = 0x40038030;
static constexpr uint32_t ADC0_SSMUX0  = 0x40038040;
static constexpr uint32_t ADC0_SSCTL0  = 0x40038044;
static constexpr uint32_t ADC0_SSFIFO0 = 0x40038048;
static constexpr uint32_t ADC0_PC      = 0x40038FC4;

/* ── SysTick (Cortex-M4 core peripheral — fixed addresses) ─────────────────── */
static constexpr uint32_t NVIC_ST_CTRL    = 0xE000E010;
static constexpr uint32_t NVIC_ST_RELOAD  = 0xE000E014;
static constexpr uint32_t NVIC_ST_CURRENT = 0xE000E018;

static volatile uint32_t g_millis = 0;

extern "C" void SysTick_Handler(void)
{
    ++g_millis;
}

static void SysTick_Init()
{
    HWREG(NVIC_ST_RELOAD)  = 16000 - 1; /* 1 ms tick @ 16 MHz PIOSC (reset default clock) */
    HWREG(NVIC_ST_CURRENT) = 0;
    HWREG(NVIC_ST_CTRL)    = (1u << 2) | (1u << 1) | (1u << 0); /* core clk, interrupt, enable */
}

static uint32_t millis()
{
    return g_millis;
}

static void delay_ms(uint32_t ms)
{
    uint32_t start = millis();
    while ((millis() - start) < ms) {}
}

/* ── UART driver ─────────────────────────────────────────────────────────── */
static void UART_Init()
{
    HWREG(SYSCTL_RCGCUART) |= (1u << 0); /* UART0 */
    for (volatile uint32_t i = 0; i < 100000 && !(HWREG(SYSCTL_PRUART) & (1u << 0)); ++i) {}

    HWREG(SYSCTL_RCGCGPIO) |= (1u << 0); /* Port A */
    for (volatile uint32_t i = 0; i < 100000 && !(HWREG(SYSCTL_PRGPIO) & (1u << 0)); ++i) {}

    HWREG(GPIOA_AFSEL) |= 0x03;
    HWREG(GPIOA_PCTL)   = (HWREG(GPIOA_PCTL) & ~0xFFu) | 0x11; /* AF1 = U0RX/U0TX */
    HWREG(GPIOA_DEN)   |= 0x03;

    HWREG(UART0_CTL)  = 0; /* disable while configuring */
    HWREG(UART0_IBRD) = 8;  /* 16MHz / (16 * 115200) = 8.68 */
    HWREG(UART0_FBRD) = 44; /* round(0.68 * 64) */
    HWREG(UART0_LCRH) = (0x3u << 5) | (1u << 4); /* 8N1, FIFO enabled */
    HWREG(UART0_CTL)  = (1u << 0) | (1u << 8) | (1u << 9); /* UARTEN, TXE, RXE */
}

static void UART_PutChar(char c)
{
    while (HWREG(UART0_FR) & UART_FR_TXFF) {}
    HWREG(UART0_DR) = static_cast<uint32_t>(c);
}

static void UART_PutStr(const char *s)
{
    while (*s) {
        UART_PutChar(*s++);
    }
}

static void UART_PutUInt(uint32_t v)
{
    char buf[10];
    int i = 0;
    if (v == 0) {
        UART_PutChar('0');
        return;
    }
    while (v > 0 && i < 10) {
        buf[i++] = static_cast<char>('0' + (v % 10));
        v /= 10;
    }
    while (i > 0) {
        UART_PutChar(buf[--i]);
    }
}

/* Prints a milli-g value (thousandths of a g) as a signed "X.XXX" string. */
static void UART_PutMilliG(int32_t milli_g)
{
    if (milli_g < 0) {
        UART_PutChar('-');
        milli_g = -milli_g;
    }
    UART_PutUInt(static_cast<uint32_t>(milli_g) / 1000);
    UART_PutChar('.');
    uint32_t frac = static_cast<uint32_t>(milli_g) % 1000;
    if (frac < 100) UART_PutChar('0');
    if (frac < 10)  UART_PutChar('0');
    UART_PutUInt(frac);
}

/* ── Analog accelerometer via ADC0 ───────────────────────────────────────────
 * The part is ratiometric — both its zero-g bias (VS/2) and its sensitivity
 * scale with its supply. The TM4C's ADC references VDDA and both rails are
 * the same 3.3 V here, so the ratio cancels and the constants below are
 * supply-independent.
 *
 * These are MEASURED on this board, not taken from a datasheet. With the
 * BoosterPack lying flat (Z vertical) the resting counts were:
 *
 *     X = 2052    Y = 2047    Z = 2876
 *
 * X and Y sit on the bias, confirming it as 2048 (= 4096/2, i.e. VS/2), and
 * Z's 828-count offset is exactly one g of gravity.
 *
 * Worth flagging: 828 counts/g is ~667 mV/g, which does NOT match the
 * ADXL326's datasheet 57 mV/g. A +-16 g part would put all of gravity in
 * 78 counts. So whatever is fitted to this BoosterPack is a low-g (~+-2 g)
 * device — check your board revision before trusting the absolute scale.
 *
 * To recalibrate (raw counts are echoed in the CSV, so no reflash needed):
 *   1. Lay the board flat and note Z            -> bias + 1 g
 *   2. Turn it upside down and note Z           -> bias - 1 g
 *   3. bias = mean of the two; counts/g = half the difference
 * Repeat per axis if you need each one's individual offset.
 */
static constexpr float ACCEL_ZERO_G_COUNTS = 2048.0f;
static constexpr float ACCEL_COUNTS_PER_G  = 828.0f;

static void ADC_Init()
{
    HWREG(SYSCTL_RCGCGPIO) |= (1u << 3); /* Port D */
    for (volatile uint32_t i = 0; i < 100000 && !(HWREG(SYSCTL_PRGPIO) & (1u << 3)); ++i) {}

    HWREG(SYSCTL_RCGCADC) |= (1u << 0); /* ADC0 */
    for (volatile uint32_t i = 0; i < 100000 && !(HWREG(SYSCTL_PRADC) & (1u << 0)); ++i) {}

    /* Hand PD0/PD1/PD2 to the analog mux. Every digital feature has to come
       off these pins — a pull-up or an open-drain setting here would fight
       the accelerometer's output buffer and skew the reading. */
    HWREG(GPIOD_DIR)   &= ~ACCEL_PINS; /* inputs — never drive these */
    HWREG(GPIOD_AFSEL) |=  ACCEL_PINS;
    HWREG(GPIOD_DEN)   &= ~ACCEL_PINS;
    HWREG(GPIOD_PUR)   &= ~ACCEL_PINS;
    HWREG(GPIOD_ODR)   &= ~ACCEL_PINS;
    HWREG(GPIOD_AMSEL) |=  ACCEL_PINS;

    HWREG(ADC0_PC)    = 0x1; /* 125 ksps — slowest, lowest-noise conversion rate */
    HWREG(ADC0_ACTSS) &= ~(1u << 0); /* disable SS0 while configuring */
    HWREG(ADC0_EMUX)  = (HWREG(ADC0_EMUX) & ~0xFu); /* SS0 trigger = software (PSSI) */
    HWREG(ADC0_SAC)   = 0x6; /* 64x hardware oversampling (~64 us/sample, ample at 20 Hz) */

    /* SS0 step order: AIN7 (X), AIN6 (Y), AIN5 (Z). */
    HWREG(ADC0_SSMUX0) = 0x00000567;
    /* Step 2 is the last one: END | IE. Steps 0 and 1 carry no flags. */
    HWREG(ADC0_SSCTL0) = 0x00000600;

    HWREG(ADC0_ACTSS) |= (1u << 0);
    HWREG(ADC0_ISC)    = (1u << 0); /* clear any stale completion flag */
}

/* Runs one SS0 pass and fills out[3] with raw X/Y/Z counts. Returns false if
   the sequencer never signalled completion (which would mean the ADC was
   misconfigured, not that the sensor is absent — an analog part can't NACK). */
static bool ADC_ReadAccelRaw(uint16_t out[3])
{
    HWREG(ADC0_PSSI) = (1u << 0); /* start SS0 */

    bool done = false;
    for (uint32_t timeout = 200000; timeout > 0; --timeout) {
        if (HWREG(ADC0_RIS) & (1u << 0)) {
            done = true;
            break;
        }
    }
    if (!done) return false;

    for (int i = 0; i < 3; ++i) {
        out[i] = static_cast<uint16_t>(HWREG(ADC0_SSFIFO0) & 0xFFF);
    }
    HWREG(ADC0_ISC) = (1u << 0);
    return true;
}

static float counts_to_g(uint16_t counts)
{
    return (static_cast<float>(counts) - ACCEL_ZERO_G_COUNTS) / ACCEL_COUNTS_PER_G;
}

/* ── Sample scheduling ───────────────────────────────────────────────────────
 * The loop runs to a fixed deadline rather than "do the work, then sleep
 * N ms". The difference matters more than it looks: the old sleep-after
 * form produced a 54 ms period from a nominal 50 ms delay, because the ADC
 * conversion and the UART write are not free. Those timestamps are what the
 * training script derives DT from, so drift here becomes a train/deploy
 * mismatch in the network's time constants.
 *
 * 100 Hz gives 50 Hz of usable bandwidth, which comfortably covers the
 * 1-15 Hz band where shake/vibration energy actually lives. Budget per
 * 10 ms tick: ~1.5 ms ADC (3 channels x 64x oversampling), ~4.5 ms UART
 * (worst-case line length at 115200), leaving decent margin. Overruns are
 * counted and reported rather than silently distorting the sample rate.
 *
 * SAMPLE_PERIOD_MS and the trained sltc_weights::DT must agree. That is
 * checked at boot rather than with a static_assert, because during data
 * collection you are deliberately running a stale weights file whose DT has
 * not been regenerated yet, and a hard build failure there would just be in
 * the way.
 */
static constexpr uint32_t SAMPLE_PERIOD_MS = 10; /* 100 Hz */
static constexpr uint32_t HEARTBEAT_TICKS  = 25; /* blue LED toggles at 4 Hz */

/* ── Entry point ─────────────────────────────────────────────────────────── */
int main(void)
{
    /* Status LED (PF1/PF2/PF3) */
    HWREG(SYSCTL_RCGCGPIO) |= (1u << 5); /* Port F */
    for (volatile uint32_t i = 0; i < 100000 && !(HWREG(SYSCTL_PRGPIO) & (1u << 5)); ++i) {}
    HWREG(GPIOF_DIR) |= (LED_RED | LED_GREEN | LED_BLUE);
    HWREG(GPIOF_DEN) |= (LED_RED | LED_GREEN | LED_BLUE);

    /* NOTE: UART must be initialized before SysTick — the reverse order
       reliably hangs the whole firmware on this toolchain/board, for
       reasons not yet root-caused. */
    UART_Init();
    SysTick_Init();

    /* Banner goes out before any peripheral init that could fault, so a
       silent board narrows to "died before this point" rather than leaving
       nothing to go on. */
    UART_PutStr("\r\n=== TM4C123G + BOOSTXL-EDUMKII Accelerometer Logger ===\r\n");

    UART_PutStr("init: ADC0 + PD0/PD1/PD2 analog ... ");
    ADC_Init();
    UART_PutStr("ok\r\n");

    /* Startup sanity read. An analog sensor can't identify itself the way an
       I2C part can, so the closest thing to a WHO_AM_I is checking that the
       axes sit near mid-scale: a railed reading (near 0 or 4095) means the
       pin isn't seeing the accelerometer at all — wrong pin, or the BoosterPack
       isn't seated. */
    uint16_t raw[3] = {0, 0, 0};
    if (!ADC_ReadAccelRaw(raw)) {
        while (true) {
            UART_PutStr("ERROR: ADC0 SS0 never completed — ADC misconfigured.\r\n");
            HWREG(GPIOF_DATA_ALL) ^= LED_RED;
            delay_ms(1000);
        }
    }

    UART_PutStr("Resting counts (expect ~2048 per axis, ~+828 on the vertical one):"
                " X=");
    UART_PutUInt(raw[0]);
    UART_PutStr(" Y=");
    UART_PutUInt(raw[1]);
    UART_PutStr(" Z=");
    UART_PutUInt(raw[2]);
    UART_PutStr("\r\n");

    for (int i = 0; i < 3; ++i) {
        if (raw[i] < 100 || raw[i] > 3995) {
            UART_PutStr("WARNING: axis ");
            UART_PutChar(static_cast<char>('X' + i));
            UART_PutStr(" is railed — check BoosterPack seating"
                        " (X/Y/Z = PD0/PD1/PD2 = AIN7/AIN6/AIN5).\r\n");
        }
    }

    {
        const uint32_t trained_ms =
            static_cast<uint32_t>(sltc_weights::DT * 1000.0f + 0.5f);
        if (trained_ms != SAMPLE_PERIOD_MS) {
            UART_PutStr("WARNING: sampling every ");
            UART_PutUInt(SAMPLE_PERIOD_MS);
            UART_PutStr(" ms but the loaded weights were trained at DT=");
            UART_PutUInt(trained_ms);
            UART_PutStr(" ms.\r\n");
            UART_PutStr("         The sltc_class column is meaningless until you"
                        " retrain at this rate. Fine for data collection.\r\n");
        }
    }

    /* Raw counts ride along so the calibration above can be redone from a
       capture without reflashing. Lines beginning with '#' are diagnostics,
       not samples — the training loader skips them. */
    UART_PutStr("time_ms,accel_x_g,accel_y_g,accel_z_g,raw_x,raw_y,raw_z,sltc_class\r\n");

    sLTCNeuron sltc;
    InputEncoder encoder;

    uint32_t next_deadline = millis() + SAMPLE_PERIOD_MS;
    uint32_t tick = 0;
    uint32_t overruns = 0;

    while (true) {
        if (ADC_ReadAccelRaw(raw)) {
            float accel_g[3] = {
                counts_to_g(raw[0]),
                counts_to_g(raw[1]),
                counts_to_g(raw[2]),
            };
            /* Encode before the network sees it. Under delta encoding this
               is what strips the gravity vector out: a slow tilt produces
               near-zero deltas, so orientation stops being a shortcut the
               classifier can cheat on. */
            float feat[sltc_weights::INPUT];
            encoder.encode(accel_g, feat);
            sltc.step(feat);
            int cls = sltc.classify(); /* 0 = smooth, 1 = turbulence */

            UART_PutUInt(millis());
            for (int i = 0; i < 3; ++i) {
                UART_PutChar(',');
                UART_PutMilliG(static_cast<int32_t>(accel_g[i] * 1000.0f));
            }
            for (int i = 0; i < 3; ++i) {
                UART_PutChar(',');
                UART_PutUInt(raw[i]);
            }
            UART_PutChar(',');
            UART_PutStr(cls == 1 ? "turbulence" : "smooth");
            UART_PutStr("\r\n");

            /* Blue = heartbeat (loop is alive), toggled at a rate the eye can
               actually resolve. Green/red = live sLTC classification, but
               only once the readout is off the fence — an unconfident call
               leaves both off rather than strobing between them. */
            uint32_t leds = HWREG(GPIOF_DATA_ALL);
            if ((tick % HEARTBEAT_TICKS) == 0) leds ^= LED_BLUE;
            leds &= ~(LED_RED | LED_GREEN);
            if (sltc.confidence() > 0.6f) {
                leds |= (cls == 1) ? LED_RED : LED_GREEN;
            }
            HWREG(GPIOF_DATA_ALL) = leds;
        } else {
            UART_PutStr("# ADC read error\r\n");
        }

        ++tick;

        /* Report loop health occasionally. If this ever climbs, the work no
           longer fits in SAMPLE_PERIOD_MS and the real sample rate is below
           what the weights were trained for. */
        if ((tick % 1000) == 0 && overruns > 0) {
            UART_PutStr("# overruns=");
            UART_PutUInt(overruns);
            UART_PutStr(" of ");
            UART_PutUInt(tick);
            UART_PutStr(" samples — loop is not keeping up\r\n");
        }

        /* Fixed-rate scheduling. Signed comparison so the millis() rollover
           at 2^32 ms (~49 days) is handled by wraparound rather than
           deadlocking the loop. On an overrun the deadline is already past,
           so resync to now instead of trying to catch up — bunching samples
           together would corrupt the timebase worse than dropping the slack. */
        if (static_cast<int32_t>(millis() - next_deadline) >= 0) {
            ++overruns;
            next_deadline = millis() + SAMPLE_PERIOD_MS;
        } else {
            while (static_cast<int32_t>(millis() - next_deadline) < 0) {}
            next_deadline += SAMPLE_PERIOD_MS;
        }
    }
}
